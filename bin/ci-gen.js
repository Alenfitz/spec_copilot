/**
 * ci-gen.js — CI/CD 配置自动生成（v3.0.0）
 *
 * 自动生成 GitHub Actions workflow，让 gate 检查在 PR 时自动执行。
 * 从"人记得跑"变成"机器强制跑"。
 */

const fs = require('fs');
const path = require('path');

/**
 * 生成 GitHub Actions workflow YAML
 */
function generateGitHubActions(projectRoot, options = {}) {
  const {
    nodeVersion = '18',
    runSmoke = true,
    runReview = true,
    hasBackend = false,
    backendType = 'spring-boot',
  } = options;

  // 自动检测项目结构
  const hasFrontend = fs.existsSync(path.join(projectRoot, 'frontend', 'package.json')) ||
                      fs.existsSync(path.join(projectRoot, 'package.json'));
  const hasJava = fs.existsSync(path.join(projectRoot, 'pom.xml')) ||
                  fs.existsSync(path.join(projectRoot, 'backend', 'pom.xml'));
  const hasFrontendDir = fs.existsSync(path.join(projectRoot, 'frontend'));

  const backendDetected = hasJava || hasBackend;

  let yaml = `# Auto-generated by @alenfitz/spec-copilot v3.0.0
# spec-copilot gate 自动化 — PR 提交时自动执行质量门禁
name: Spec Gate

on:
  pull_request:
    branches: [main, master, develop]
    paths-ignore:
      - '*.md'
      - 'docs/**'

jobs:
  gate-check:
    runs-on: ubuntu-latest
    timeout-minutes: 15

    steps:
      - uses: actions/checkout@v4

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '${nodeVersion}'
          cache: 'npm'${hasFrontendDir ? `
          cache-dependency-path: frontend/package-lock.json` : ''}
`;

  if (backendDetected && hasJava) {
    yaml += `
      - name: Setup Java
        uses: actions/setup-java@v4
        with:
          java-version: '17'
          distribution: 'temurin'
          cache: 'maven'
`;
  }

  // Install dependencies
  if (hasFrontendDir) {
    yaml += `
      - name: Install frontend dependencies
        run: cd frontend && npm ci
`;
  } else if (hasFrontend) {
    yaml += `
      - name: Install dependencies
        run: npm ci
`;
  }

  // Install Chrome for E2E
  yaml += `
      - name: Install Chrome
        uses: browser-actions/setup-chrome@v1
        with:
          chrome-version: stable
`;

  // Detect change name from PR
  yaml += `
      - name: Detect change name
        id: detect
        run: |
          # 从分支名或 PR title 提取变更名
          BRANCH=\${{ github.head_ref }}
          # 去掉 feature/ 等前缀
          CHANGE_NAME=\${BRANCH#feature/}
          CHANGE_NAME=\${CHANGE_NAME#feat/}
          CHANGE_NAME=\${CHANGE_NAME#fix/}
          echo "change_name=$CHANGE_NAME" >> $GITHUB_OUTPUT

          # 检查变更目录是否存在
          if [ -d "spec_copilot/changes/$CHANGE_NAME" ]; then
            echo "has_spec=true" >> $GITHUB_OUTPUT
          else
            echo "has_spec=false" >> $GITHUB_OUTPUT
            echo "::warning::未找到 spec_copilot/changes/$CHANGE_NAME — 跳过 gate 检查"
          fi
`;

  if (runSmoke) {
    yaml += `
      - name: Gate Smoke
        if: steps.detect.outputs.has_spec == 'true'
        run: npx @alenfitz/spec-copilot gate \${{ steps.detect.outputs.change_name }} smoke --no-e2e
        # --no-e2e: CI 中跳过 E2E 浏览器测试（无运行中的 dev server）
        # 如需 CI 中运行 E2E，去掉 --no-e2e 并添加服务器启动步骤
`;
  }

  if (runReview) {
    yaml += `
      - name: Gate Review
        if: steps.detect.outputs.has_spec == 'true'
        run: npx @alenfitz/spec-copilot gate \${{ steps.detect.outputs.change_name }} review
`;
  }

  // Upload score artifacts
  yaml += `
      - name: Upload gate scores
        if: always() && steps.detect.outputs.has_spec == 'true'
        uses: actions/upload-artifact@v4
        with:
          name: gate-scores
          path: spec_copilot/changes/\${{ steps.detect.outputs.change_name }}/.gate-*-score.json
          if-no-files-found: ignore
`;

  return yaml;
}

/**
 * 生成完整 CI（包含 E2E）的 workflow
 */
function generateFullE2EWorkflow(projectRoot) {
  const hasFrontendDir = fs.existsSync(path.join(projectRoot, 'frontend'));
  const hasJava = fs.existsSync(path.join(projectRoot, 'pom.xml')) ||
                  fs.existsSync(path.join(projectRoot, 'backend', 'pom.xml'));

  let yaml = `# Auto-generated by @alenfitz/spec-copilot v3.0.0
# 完整 E2E 测试（含前后端启动 + 浏览器测试）
name: Spec Gate E2E

on:
  pull_request:
    branches: [main, master]

jobs:
  gate-e2e:
    runs-on: ubuntu-latest
    timeout-minutes: 30

    steps:
      - uses: actions/checkout@v4

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '18'
`;

  if (hasJava) {
    yaml += `
      - name: Setup Java
        uses: actions/setup-java@v4
        with:
          java-version: '17'
          distribution: 'temurin'
          cache: 'maven'
`;
  }

  if (hasFrontendDir) {
    yaml += `
      - name: Install frontend dependencies
        run: cd frontend && npm ci
`;
  }

  yaml += `
      - name: Install Chrome
        uses: browser-actions/setup-chrome@v1
        with:
          chrome-version: stable

      - name: Detect change name
        id: detect
        run: |
          BRANCH=\${{ github.head_ref }}
          CHANGE_NAME=\${BRANCH#feature/}
          CHANGE_NAME=\${CHANGE_NAME#feat/}
          CHANGE_NAME=\${CHANGE_NAME#fix/}
          echo "change_name=$CHANGE_NAME" >> $GITHUB_OUTPUT
          [ -d "spec_copilot/changes/$CHANGE_NAME" ] && echo "has_spec=true" >> $GITHUB_OUTPUT || echo "has_spec=false" >> $GITHUB_OUTPUT
`;

  // Start backend
  if (hasJava) {
    yaml += `
      - name: Start backend
        if: steps.detect.outputs.has_spec == 'true'
        run: |
          cd ${fs.existsSync(path.join(projectRoot, 'backend', 'pom.xml')) ? 'backend' : '.'}
          mvn spring-boot:run -q &
          # 等待后端就绪
          for i in $(seq 1 60); do curl -sf http://localhost:8080/actuator/health && break || sleep 2; done
`;
  }

  // Start frontend
  yaml += `
      - name: Start frontend
        if: steps.detect.outputs.has_spec == 'true'
        run: |
          cd ${hasFrontendDir ? 'frontend' : '.'}
          npm run dev &
          sleep 5
`;

  yaml += `
      - name: Gate Smoke (with E2E)
        if: steps.detect.outputs.has_spec == 'true'
        run: npx @alenfitz/spec-copilot gate \${{ steps.detect.outputs.change_name }} smoke --base-url http://localhost:5173${hasJava ? ' --backend-url http://localhost:8080' : ''}

      - name: Gate Review
        if: steps.detect.outputs.has_spec == 'true'
        run: npx @alenfitz/spec-copilot gate \${{ steps.detect.outputs.change_name }} review
`;

  return yaml;
}

/**
 * 安装 CI 配置到项目
 */
function cmdCISetup(projectRoot, options = {}) {
  const workflowDir = path.join(projectRoot, '.github', 'workflows');
  if (!fs.existsSync(workflowDir)) {
    fs.mkdirSync(workflowDir, { recursive: true });
  }

  const basicPath = path.join(workflowDir, 'spec-gate.yml');
  const basicYaml = generateGitHubActions(projectRoot, options);
  fs.writeFileSync(basicPath, basicYaml);
  console.log(`  ✅ ${path.relative(projectRoot, basicPath)}`);

  if (options.withE2E) {
    const e2ePath = path.join(workflowDir, 'spec-gate-e2e.yml');
    const e2eYaml = generateFullE2EWorkflow(projectRoot);
    fs.writeFileSync(e2ePath, e2eYaml);
    console.log(`  ✅ ${path.relative(projectRoot, e2ePath)}`);
  }

  console.log('');
  console.log('  💡 Gate 检查将在 PR 提交时自动执行');
  console.log('  💡 修改 .github/workflows/spec-gate.yml 自定义行为');
}

module.exports = {
  generateGitHubActions,
  generateFullE2EWorkflow,
  cmdCISetup,
};
